/// テスト用の日記([TestDiaryGenerator])と同じ期間に、1日0〜3件(平均1.3件ほど)。
/// 平日は仕事、休日は趣味や外出の話題で、旅行や特別な日は、その日の出来事。
/// URLが[urlPrefix]で始まる投稿が、テスト用の投稿(削除のときの目印)
