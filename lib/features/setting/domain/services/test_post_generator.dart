  /// [first]から[last]まで。同じ入力なら、いつも同じ投稿ができる
  static List<SharedPost> generate({
    required DateTime first,
    required DateTime last,
  }) {
    final posts = <SharedPost>[];
    var index = 0;
    var serial = 0;

    for (
      var day = DateTime(first.year, first.month, first.day);
      !day.isAfter(last);
      day = DateTime(day.year, day.month, day.day + 1), index++
    ) {
      final texts = _textsOf(day, index);

      for (var i = 0; i < texts.length; i++) {
        final time = _times[(index + i) % _times.length];

        posts.add(
          SharedPost(
            url: "$urlPrefix${1900000000000000000 + serial}",
            text: texts[i],
            receivedAt: DateTime(
              day.year,
              day.month,
              day.day,
              time.$1,
              time.$2,
            ),
          ),
        );
        serial++;
      }
    }

    return posts;
  }

