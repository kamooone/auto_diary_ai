/// 料理、旅行、家族や友人)があり、平日と休日で書く内容が違い、決まった日には、
/// その日だけの出来事が入る。
/// タイトルが[titlePrefix]で始まる日記が、テスト用の日記
class TestDiaryGenerator {
  const TestDiaryGenerator._();

  static const titlePrefix = "【テスト】";

  static bool isTestDiary(Diary diary) => diary.title.startsWith(titlePrefix);

  /// [first]から[last]まで、1日1件(各400文字前後。旅行の日は短め)
  static List<Diary> generate({required DateTime first, required DateTime last}) {
    final diaries = <Diary>[];
    var index = 0;

    for (
      var day = DateTime(first.year, first.month, first.day);
      !day.isAfter(last);
      day = DateTime(day.year, day.month, day.day + 1), index++
    ) {
      final entry = _entry(day, index);

      diaries.add(
        Diary(
          date: day,
          title: "$titlePrefix${entry.title}",
          content: entry.content,
          isAiGenerated: false,
          createdAt: DateTime(day.year, day.month, day.day, 21),
        ),
      );
    }

    return diaries;
  }

  static ({String title, String content}) _entry(DateTime day, int index) {
    // 同じ日に、同じ文が2回入らないようにする
    final used = <String>{};

    String pick(List<String> list, int stride, int offset) {
      for (var i = 0; i < list.length; i++) {
        final sentence = list[(index * stride + offset + i) % list.length];
        if (used.add(sentence)) return sentence;
      }
      return list[(index * stride + offset) % list.length];
    }

    final m = (day.month - 1) % 10 + 1;
    final isWeekday = day.weekday <= 5;
    final special = _specials["${day.month}/${day.day}"];
    final season = switch (day.month) {
      12 || 1 || 2 => _winter,
      3 || 4 || 5 => _spring,
      6 || 7 || 8 || 9 => _summer,
      _ => _autumn,
    };

    final String title;
    final List<String> sentences;

    if (special != null) {
      title = special.title;

      // 旅行の日は、出かけた内容がその日の中心なので、ほかの普段の出来事は少なくする
      final isTrip = _tripDays.contains("${day.month}/${day.day}");

      sentences = [
        pick(season, 1, 0),
        if (!isTrip) pick(isWeekday ? _commute : _weekendMorning, 3, 1),
        special.text,
        if (!isTrip) pick(_lunch, 5, 4),
        if (!isTrip && isWeekday) pick(_work[m]!, 1, 0),
        pick(_hobby[m]!, 1, 2),
        if (!isTrip) pick(_hobby[m]!, 1, 0),
        pick(isWeekday ? _weekdayEvening : _weekendPeople, 3, 1),
        if (!isTrip) pick(_homeEvening, 3, 1),
        pick(_reflection, 5, 4),
        pick(_reflection, 7, 8),
      ];
    } else if (isWeekday) {
      title = _weekdayTitles[m]![index % 3];
      sentences = [
        pick(season, 1, 0),
        pick(_commute, 3, 1),
        pick(_work[m]!, 1, 0),
        pick(_work[m]!, 1, 3),
        pick(_commonWork, 3, 2),
        pick(_work[m]!, 1, 5),
        pick(_lunch, 5, 4),
        pick(_hobby[m]!, 1, 1),
        pick(_weekdayEvening, 5, 2),
        pick(_weekdayEvening, 7, 6),
        pick(_homeEvening, 3, 1),
        pick(_hobby[m]!, 1, 3),
        pick(_reflection, 5, 3),
        pick(_reflection, 7, 8),
      ];
    } else {
      title = _weekendTitles[index % _weekendTitles.length];
      sentences = [
        pick(season, 1, 0),
        pick(_weekendMorning, 1, 2),
        pick(_weekendOuting, 3, 1),
        pick(_weekendOuting, 7, 9),
        pick(_weekendOuting, 5, 14),
        pick(_lunch, 5, 4),
        pick(_hobby[m]!, 1, 0),
        pick(_hobby[m]!, 1, 2),
        pick(_weekendPeople, 3, 2),
        pick(_weekendPeople, 7, 7),
        pick(_homeEvening, 3, 1),
        pick(_hobby[m]!, 1, 3),
        pick(_reflection, 5, 3),
        pick(_reflection, 7, 8),
      ];
    }

    return (
      title: title,
      content: "${day.month}月${day.day}日。${sentences.join()}",
    );
  }

